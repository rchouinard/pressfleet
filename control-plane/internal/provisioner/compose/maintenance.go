// Maintenance mode (#44, design doc §5.4).
//
// A site's own routes are labels on its nginx container; changing them
// means recreating the container, and they disappear when it stops or is
// unhealthy. Maintenance mode instead adds a file to Traefik's file
// provider directory (ProvisionerConfig.TraefikDynamicDir) with a twin of
// each of the site's routers, at a higher priority, pointing at the
// platform's maintenance page (package ingress). Traefik watches the
// directory, so adding or removing the file takes effect within a couple
// of seconds, and the page stays up whatever the site's containers are
// doing, which is what restores and rollouts need.
//
// RenderSite writes the file's content into the site's directory
// (SiteMaintenanceFile) every time it renders, so it follows the site's
// domains; SetMaintenance copies it into Traefik's directory or removes
// it, and converge does the same from SiteConfig.Maintenance.

// SiteMaintenanceFile is the site's maintenance routes, which RenderSite
// writes into the site's directory and SetMaintenance hands to Traefik.
const SiteMaintenanceFile = "traefik-maintenance.yaml"

// ErrMaintenanceUnavailable means the platform has no maintenance page to
// send visitors to: the provisioner has no Traefik file provider directory,
// or the platform was rendered by a version without one.
var ErrMaintenanceUnavailable = errors.New("compose: maintenance mode is unavailable")

// MaintenanceRoutesFile is the name of the file in Traefik's file provider
// directory that holds a site's maintenance routes while it is in
// maintenance mode.
func MaintenanceRoutesFile(siteID string) string {
	return ingress.SiteName(siteID, ingress.SuffixMaintenance) + ".yaml"
}

// fileRouter is a router in Traefik's file provider format.
type fileRouter struct {
	Rule        string   `yaml:"rule"`
	EntryPoints []string `yaml:"entryPoints"`
	Priority    int      `yaml:"priority,omitempty"`
	Middlewares []string `yaml:"middlewares,omitempty"`
	Service     string   `yaml:"service"`
	TLS         struct {
		CertResolver string `yaml:"certResolver"`
	} `yaml:"tls"`
}

// maintenanceRoutes renders the site's maintenance routes: a twin of each
// of its routers (siteRouters), with the same rule, entry point, and
// certificate resolver, sending everything to the maintenance page. The
// twins have none of the site's middlewares, which belong to the site's
// containers and vanish with them; the page is public and holds nothing.
func maintenanceRoutes(site *provisioner.SiteConfig) ([]byte, error) {
	routers := map[string]fileRouter{}
	for _, r := range siteRouters(site, false) {
		m := fileRouter{
			Rule:        r.Rule,
			EntryPoints: []string{ingress.EntryPointHTTPS},
			Priority:    ingress.MaintenancePriority,
			Service:     ingress.MaintenanceService + "@file",
		}
		m.TLS.CertResolver = r.CertResolver
		routers[r.Name+"-"+ingress.SuffixMaintenance] = m
	}
	body, err := yaml.Marshal(map[string]any{"http": map[string]any{"routers": routers}})
	if err != nil {
		return nil, err
	}
	header := "# Maintenance routes of PressFleet site " + site.ID + " (design doc §5.4).\n" +
		"#\n" +
		"# Generated by the control plane. While the site is in maintenance mode, a copy\n" +
		"# is in Traefik's file provider directory, and its domains get the maintenance\n" +
		"# page. Do not edit: changes are overwritten the next time the site is rendered.\n"
	return append([]byte(header), body...), nil
}

// SetMaintenance puts the site's domains on the platform's maintenance page
// or takes them off it. See the comment at the top of this file.
func (p *Provisioner) SetMaintenance(ctx context.Context, siteID string, enabled bool) error {
	if err := validSiteID(siteID); err != nil {
		return fmt.Errorf("set maintenance: %w", err)
	}
	changed, err := p.applyMaintenance(siteID, enabled)
	if err != nil {
		return fmt.Errorf("set maintenance of site %s: %w", siteID, err)
	}
	if changed {
		p.log.InfoContext(ctx, "site maintenance mode changed", "site_id", siteID, "enabled", enabled)
	}
	return nil
}

// applyMaintenance installs or removes the site's maintenance routes in
// Traefik's directory, reporting whether anything changed. Installing
// needs the rendered routes; removing works for any site.
func (p *Provisioner) applyMaintenance(siteID string, enabled bool) (bool, error) {
	if p.routesDir == "" {
		if !enabled {
			return false, nil
		}
		return false, fmt.Errorf("%w: no Traefik file provider directory is configured", ErrMaintenanceUnavailable)
	}
	target := filepath.Join(p.routesDir, MaintenanceRoutesFile(siteID))
	if !enabled {
		err := os.Remove(target)
		if errors.Is(err, fs.ErrNotExist) {
			return false, nil
		}
		return err == nil, err
	}
	if fi, err := os.Stat(p.routesDir); err != nil || !fi.IsDir() {
		return false, fmt.Errorf("%w: %s doesn't exist; re-render the platform with this version (pressfleet init --force)",
			ErrMaintenanceUnavailable, p.routesDir)
	}
	dir, err := p.layout.SiteDir(siteID)
	if err != nil {
		return false, fmt.Errorf("%w: %w", ErrInvalidSite, err)
	}
	routes, err := os.ReadFile(filepath.Join(dir, SiteMaintenanceFile)) //nolint:gosec // G304: inside the site's directory
	if errors.Is(err, fs.ErrNotExist) {
		return false, fmt.Errorf("the site has no rendered routes: %w", provisioner.ErrSiteNotFound)
	}
	if err != nil {
		return false, err
	}
	// Traefik (root without CAP_DAC_OVERRIDE) must be able to read it; it
	// holds nothing secret. The temporary file replaceFile writes first has
	// no .yaml extension, so Traefik ignores it.
	return replaceFile(target, routes, 0o644, -1)
}
