// Custom domains (#45, #46, design doc §5.2).
//
// A live site's primary domain and aliases are routed from a file in
// Traefik's file provider directory (ProvisionerConfig.TraefikDynamicDir),
// not from nginx's labels: changing a label recreates nginx, and the site
// is unreachable until the new container is healthy, while Traefik picks up
// a changed file within a couple of seconds without touching the site. So
// going live and changing domains cause no downtime. The file's routers
// send requests to the service nginx's labels define (pf-<site-id>@docker)
// and define every middleware they use themselves; package ingress
// documents the names.
//
// Like the maintenance routes, RenderSite writes the file into the site's
// directory (SiteDomainsFile), where operators can read it, and converge
// copies it into Traefik's directory, or removes it there when the site
// has no primary domain.

// SiteDomainsFile is the site's custom domain routes, which RenderSite
// writes into the site's directory for a live site.
const SiteDomainsFile = "traefik-domains.yaml"

// ErrDomainsUnavailable means the platform can't route custom domains: the
// provisioner has no Traefik file provider directory, or the platform was
// rendered by a version without one.
var ErrDomainsUnavailable = errors.New("compose: custom domains are unavailable")

// DomainRoutesFile is the name of the file in Traefik's file provider
// directory that holds a live site's custom domain routes.
func DomainRoutesFile(siteID string) string {
	return ingress.SiteName(siteID, ingress.SuffixDomains) + ".yaml"
}

// redirectRegex matches any URL Traefik sees and captures its path and
// query, which a redirect to the primary domain keeps.
const redirectRegex = `^https?://[^/]+(.*)$`

// domainRoutes renders the site's custom domain routes, or nil if the site
// isn't live. hsts adds the HSTS middleware to the primary domain and
// aliases (§6.1).
func domainRoutes(site *provisioner.SiteConfig, hsts bool) ([]byte, error) {
	if site.PrimaryDomain == "" {
		return nil, nil
	}
	service := ingress.SiteService(site.ID) + "@docker"
	name := func(suffixes ...string) string { return ingress.SiteName(site.ID, suffixes...) }
	routers := map[string]fileRouter{}
	for _, r := range siteRouters(site, hsts) {
		if !r.Domain {
			continue
		}
		fr := fileRouter{Rule: r.Rule, EntryPoints: []string{ingress.EntryPointHTTPS}, Middlewares: r.Middlewares, Service: service}
		fr.TLS.CertResolver = r.CertResolver
		routers[r.Name] = fr
	}
	// The preview domain now redirects to the primary domain, behind the
	// preview router's own middlewares, so a protected preview domain asks
	// for the password before it reveals where the site went.
	preview := fileRouter{
		Rule:        hostRule(site.PreviewDomain),
		EntryPoints: []string{ingress.EntryPointHTTPS},
		Priority:    ingress.PreviewRedirectPriority,
		Middlewares: append(previewMiddlewares(site), name(ingress.SuffixPreviewRedirect)),
		Service:     service,
	}
	preview.TLS.CertResolver = ingress.CertResolverPreview
	routers[name(ingress.SuffixPreviewRedirect)] = preview

	redirect := map[string]any{"redirectRegex": map[string]any{
		"regex":       redirectRegex,
		"replacement": "https://" + site.PrimaryDomain + "${1}",
		"permanent":   true,
	}}
	middlewares := map[string]any{
		name(ingress.SuffixPreviewRedirect): redirect,
		name(ingress.SuffixAliasRedirect):   redirect,
		// Copies of the preview router's middlewares from nginx's labels,
		// so the file depends on nothing of the site but its service.
		name(ingress.SuffixNoIndex): map[string]any{"headers": map[string]any{
			"customResponseHeaders": map[string]string{"X-Robots-Tag": "noindex"},
		}},
	}
	if hsts {
		// Without includeSubDomains: a client's other subdomains may not
		// serve HTTPS (§6.1).
		middlewares[name(ingress.SuffixHSTS)] = map[string]any{"headers": map[string]any{
			"stsSeconds": ingress.HSTSMaxAge,
		}}
	}
	if a := site.PreviewAuth; a != nil {
		middlewares[name(ingress.SuffixPreviewAuth)] = map[string]any{"basicAuth": map[string]any{
			"users":        []string{a.Username + ":" + a.PasswordHash},
			"removeHeader": true,
			"realm":        "Preview",
		}}
	}
	body, err := yaml.Marshal(map[string]any{"http": map[string]any{"routers": routers, "middlewares": middlewares}})
	if err != nil {
		return nil, err
	}
	header := "# Custom domain routes of PressFleet site " + site.ID + " (design doc §5.2).\n" +
		"#\n" +
		"# Generated by the control plane. A copy is in Traefik's file provider\n" +
		"# directory while the site is live. Do not edit: changes are overwritten the\n" +
		"# next time the site is rendered.\n"
	return append([]byte(header), body...), nil
}

// applyDomains installs the site's rendered custom domain routes in
// Traefik's directory, or removes them if the site isn't live, reporting
// whether anything changed. Removing works for any site.
func (p *Provisioner) applyDomains(siteID string, live bool) (bool, error) {
	target := ""
	if p.routesDir != "" {
		target = filepath.Join(p.routesDir, DomainRoutesFile(siteID))
	}
	if !live {
		if target == "" {
			return false, nil
		}
		err := os.Remove(target)
		if errors.Is(err, fs.ErrNotExist) {
			return false, nil
		}
		return err == nil, err
	}
	if target == "" {
		return false, fmt.Errorf("%w: no Traefik file provider directory is configured", ErrDomainsUnavailable)
	}
	if fi, err := os.Stat(p.routesDir); err != nil || !fi.IsDir() {
		return false, fmt.Errorf("%w: %s doesn't exist; re-render the platform with this version (pressfleet init --force)",
			ErrDomainsUnavailable, p.routesDir)
	}
	dir, err := p.layout.SiteDir(siteID)
	if err != nil {
		return false, fmt.Errorf("%w: %w", ErrInvalidSite, err)
	}
	routes, err := os.ReadFile(filepath.Join(dir, SiteDomainsFile)) //nolint:gosec // G304: inside the site's directory
	if err != nil {
		return false, err
	}
	// Readable by Traefik, like the maintenance routes. It holds nothing
	// secret: the preview password's bcrypt hash is in nginx's labels too.
	return replaceFile(target, routes, 0o644, -1)
}
