// Package charts holds PressFleet's Helm chart, charts/pressfleet (design
// doc §4.8), and the Go side of it: the files the chart shares with the
// platform Compose project, and the chart's tests.
//
// The chart pins the same images as the Compose project, and configures
// MariaDB and Valkey from the same templates, by carrying copies of those
// files from templates/platform. The copies are generated, never edited by
// hand: run `make generate` after changing a source. A test fails if a copy
// has drifted.
package charts

import (
	"bytes"
	"fmt"
	"io/fs"

	"github.com/rchouinard/pressfleet/templates"
)

//go:generate go run ./internal/gen

// ChartDir is the chart's directory, relative to this package's.
const ChartDir = "pressfleet"

// SharedFile is a file of the chart copied from templates/platform.
type SharedFile struct {
	// Chart is the file's path in the chart.
	Chart string
	// Platform is the source's name in templates/platform.
	Platform string
}

// SharedFiles are the chart's copies of platform files. The chart renders
// the .tmpl files with Helm's tpl, which uses the same template language as
// the Compose renderer; they must only use fields, not the renderer's
// functions.
var SharedFiles = []SharedFile{
	{Chart: "files/images.yaml", Platform: "images.yaml"},
	{Chart: "files/mariadb.cnf.tmpl", Platform: "mariadb.cnf.tmpl"},
	{Chart: "files/valkey.conf.tmpl", Platform: "valkey.conf.tmpl"},
}

// Shared returns the content a shared file must have: a header naming its
// source, then the source.
func Shared(f SharedFile) ([]byte, error) {
	src, err := fs.ReadFile(templates.Platform(), f.Platform)
	if err != nil {
		return nil, fmt.Errorf("reading platform file: %w", err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by `make generate` from templates/platform/%s. Do not edit.\n", f.Platform)
	b.Write(src)
	return b.Bytes(), nil
}
